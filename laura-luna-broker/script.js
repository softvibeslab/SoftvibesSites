let currentLanguage = localStorage.getItem("laura-language") === "en" ? "en" : "es";

function track(event, details = {}) {
  window.dataLayer = window.dataLayer || [];
  window.dataLayer.push({ event, page_language: currentLanguage, ...details });
}

function setLanguage(language) {
  currentLanguage = language;
  const dictionary = translations[language];

  document.documentElement.lang = language;
  document.querySelectorAll("[data-i18n]").forEach((element) => {
    const value = dictionary[element.dataset.i18n];
    if (value) element.textContent = value;
  });
  document.querySelectorAll("[data-i18n-html]").forEach((element) => {
    const value = dictionary[element.dataset.i18nHtml];
    if (value) element.innerHTML = value;
  });

  const toggle = document.querySelector("[data-language]");
  toggle.textContent = language === "es" ? "EN" : "ES";
  toggle.setAttribute("aria-label", language === "es" ? "Cambiar a inglés" : "Switch to Spanish");
  document.title = language === "es"
    ? "Laura Luna · Broker inmobiliaria en Riviera Maya"
    : "Laura Luna · Real estate broker in Riviera Maya";
  localStorage.setItem("laura-language", language);
}

const languageToggle = document.querySelector("[data-language]");
languageToggle.addEventListener("click", () => {
  const nextLanguage = currentLanguage === "es" ? "en" : "es";
  setLanguage(nextLanguage);
  track("language_change", { selected_language: nextLanguage });
});

const menuButton = document.querySelector("[data-menu]");
const navigation = document.querySelector("[data-nav]");

function closeMenu() {
  menuButton.setAttribute("aria-expanded", "false");
  navigation.classList.remove("open");
  document.body.classList.remove("menu-open");
}

menuButton.addEventListener("click", () => {
  const willOpen = menuButton.getAttribute("aria-expanded") !== "true";
  menuButton.setAttribute("aria-expanded", String(willOpen));
  navigation.classList.toggle("open", willOpen);
  document.body.classList.toggle("menu-open", willOpen);
});

navigation.querySelectorAll("a").forEach((link) => link.addEventListener("click", closeMenu));
window.addEventListener("resize", () => {
  if (window.innerWidth > 850) closeMenu();
});

const header = document.querySelector("[data-header]");
window.addEventListener("scroll", () => header.classList.toggle("scrolled", window.scrollY > 12), { passive: true });

const reducedMotion = window.matchMedia("(prefers-reduced-motion: reduce)").matches;
const revealItems = document.querySelectorAll(".reveal");
if (reducedMotion || !("IntersectionObserver" in window)) {
  revealItems.forEach((item) => item.classList.add("visible"));
} else {
  const observer = new IntersectionObserver((entries, instance) => {
    entries.forEach((entry) => {
      if (!entry.isIntersecting) return;
      entry.target.classList.add("visible");
      instance.unobserve(entry.target);
    });
  }, { threshold: 0.12 });
  revealItems.forEach((item) => observer.observe(item));
}

document.querySelectorAll("[data-wa]").forEach((link) => {
  link.addEventListener("click", () => track("whatsapp_click", { placement: link.dataset.wa }));
});

const leadForm = document.querySelector("[data-lead-form]");
leadForm.addEventListener("submit", (event) => {
  event.preventDefault();
  if (!leadForm.reportValidity()) return;

  const data = new FormData(leadForm);
  const intent = String(data.get("intent") || "comprar");
  const name = String(data.get("name") || "").trim();
  const budget = String(data.get("budget") || "").trim();
  const timeline = String(data.get("timeline") || "").trim();
  const note = String(data.get("note") || "").trim();
  const intentLabel = {
    es: { comprar: "comprar", vender: "vender", rentar: "rentar", invertir: "invertir" },
    en: { comprar: "buy", vender: "sell", rentar: "rent", invertir: "invest" }
  }[currentLanguage][intent];
  const timelineLabel = currentLanguage === "en"
    ? ({ "este mes": "this month", "1 a 3 meses": "1 to 3 months", "3 a 6 meses": "3 to 6 months", "solo estoy explorando": "I am just exploring" }[timeline] || timeline)
    : timeline;
  const message = currentLanguage === "es"
    ? `Hola Laura, vi tu landing personal. Soy ${name} y me interesa ${intentLabel}. Mi presupuesto aproximado es ${budget} y mi plazo es ${timelineLabel}.${note ? ` Contexto adicional: ${note}` : ""}`
    : `Hi Laura, I found your personal landing page. My name is ${name} and I am looking to ${intentLabel}. My approximate budget is ${budget}, and my timeline is ${timelineLabel}.${note ? ` Additional context: ${note}` : ""}`;

  track("qualified_whatsapp_lead", { intent, timeline, source: "personal_landing_form" });
  window.open(`https://wa.me/529841674704?text=${encodeURIComponent(message)}`, "_blank", "noopener");
});


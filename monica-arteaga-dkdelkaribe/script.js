const htmlKeys = new Set([
  "heroTitle", "personalTitle", "introTitle", "amenitiesTitle", "unitsTitle", "locationTitle",
  "paymentsTitle", "planOne", "planTwo", "planThree", "contactTitle"
]);

let currentLanguage = localStorage.getItem("dk44-language") === "en" ? "en" : "es";

function whatsappUrl(message) {
  return `https://wa.me/${phone}?text=${encodeURIComponent(message)}`;
}

function track(event, details = {}) {
  window.dataLayer = window.dataLayer || [];
  window.dataLayer.push({ event, page_language: currentLanguage, brand: "monica_arteaga_x_dk", ...details });
}

function updateWhatsappLinks() {
  document.querySelectorAll(".wa-link").forEach((link) => {
    const message = currentLanguage === "en" ? link.dataset.contextEn : link.dataset.contextEs;
    link.href = whatsappUrl(message);
    link.target = "_blank";
    link.rel = "noopener noreferrer";
  });
}

function setLanguage(language) {
  currentLanguage = language;
  localStorage.setItem("dk44-language", language);
  document.documentElement.lang = language;
  document.title = language === "en" ? "Monica Arteaga × DK del Karibe | DK44" : "Mónica Arteaga × DK del Karibe | DK44";

  document.querySelectorAll("[data-i18n]").forEach((element) => {
    const key = element.dataset.i18n;
    if (!copy[language][key]) return;
    if (htmlKeys.has(key)) element.innerHTML = copy[language][key];
    else element.textContent = copy[language][key];
  });

  document.querySelectorAll("[data-es][data-en]").forEach((element) => {
    element.textContent = element.dataset[language];
  });

  document.querySelectorAll("[data-language-toggle]").forEach((button) => {
    const spans = button.querySelectorAll("span");
    spans[0]?.classList.toggle("active", language === "es");
    spans[1]?.classList.toggle("active", language === "en");
    button.setAttribute("aria-label", language === "en" ? "Switch language to Spanish" : "Cambiar idioma a inglés");
  });

  const nameInput = document.querySelector('input[name="name"]');
  const messageInput = document.querySelector('textarea[name="message"]');
  if (nameInput) nameInput.placeholder = language === "en" ? "Your name" : "Tu nombre";
  if (messageInput) messageInput.placeholder = language === "en" ? "Tell me what information you need" : "Cuéntame qué información necesitas";

  updateWhatsappLinks();
}

document.querySelectorAll("[data-language-toggle]").forEach((button) => {
  button.addEventListener("click", () => {
    const nextLanguage = currentLanguage === "es" ? "en" : "es";
    setLanguage(nextLanguage);
    track("language_change", { selected_language: nextLanguage });
  });
});

document.querySelectorAll(".wa-link").forEach((link) => {
  link.addEventListener("click", () => {
    const section = link.closest("section")?.id || (link.classList.contains("floating-wa") ? "floating" : "header");
    track("whatsapp_click", { placement: section, source: "personal_landing" });
  });
});

const menuButton = document.querySelector(".menu-toggle");
const navigation = document.querySelector(".main-nav");

function closeMenu() {
  if (!menuButton || !navigation) return;
  menuButton.setAttribute("aria-expanded", "false");
  navigation.classList.remove("open");
  document.body.classList.remove("menu-open");
}

menuButton?.addEventListener("click", () => {
  const open = menuButton.getAttribute("aria-expanded") === "true";
  menuButton.setAttribute("aria-expanded", String(!open));
  navigation?.classList.toggle("open", !open);
  document.body.classList.toggle("menu-open", !open);
});

navigation?.querySelectorAll("a").forEach((link) => link.addEventListener("click", closeMenu));
window.addEventListener("resize", () => { if (window.innerWidth > 760) closeMenu(); });

const leadForm = document.querySelector("#lead-form");
leadForm?.addEventListener("submit", (event) => {
  event.preventDefault();
  if (!leadForm.reportValidity()) return;
  const formData = new FormData(leadForm);
  const interestSelect = leadForm.querySelector('select[name="interest"]');
  const budgetSelect = leadForm.querySelector('select[name="budget"]');
  const interest = interestSelect?.selectedOptions[0]?.textContent.trim() || "DK44";
  const budget = budgetSelect?.selectedOptions[0]?.textContent.trim() || "";

  const lines = currentLanguage === "en"
    ? [
        "Hi Monica, I found your personal landing page with DK del Karibe.",
        `Name: ${formData.get("name")}`,
        `WhatsApp: ${formData.get("phone")}`,
        `Interested in: ${interest}`,
        `Budget: ${budget}`,
        formData.get("message") ? `Message: ${formData.get("message")}` : ""
      ]
    : [
        "Hola Mónica, llegué desde tu landing personal con DK del Karibe.",
        `Nombre: ${formData.get("name")}`,
        `WhatsApp: ${formData.get("phone")}`,
        `Me interesa: ${interest}`,
        `Presupuesto: ${budget}`,
        formData.get("message") ? `Mensaje: ${formData.get("message")}` : ""
      ];

  track("qualified_whatsapp_lead", { interest, budget, source: "personal_landing_form" });
  window.open(whatsappUrl(lines.filter(Boolean).join("\n")), "_blank", "noopener,noreferrer");
});

const revealElements = document.querySelectorAll(".reveal");
if ("IntersectionObserver" in window && !window.matchMedia("(prefers-reduced-motion: reduce)").matches) {
  const observer = new IntersectionObserver((entries) => {
    entries.forEach((entry) => {
      if (entry.isIntersecting) {
        entry.target.classList.add("is-visible");
        observer.unobserve(entry.target);
      }
    });
  }, { threshold: 0.1, rootMargin: "0px 0px -40px" });
  revealElements.forEach((element) => observer.observe(element));
} else {
  revealElements.forEach((element) => element.classList.add("is-visible"));
}

